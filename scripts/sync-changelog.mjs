// Writes src/lib/changelog.generated.ts from the app repo, so the changelog on /roadmap
// keeps up with the app by itself.
//
//   node scripts/sync-changelog.mjs <path to a NetRelish checkout with tags>
//
// Released: one entry per docs/releases/vX.Y.Z.md whose tag exists, newest first.
//   Its intro is the file's first paragraph; Added is its "## New in" list.
// Unreleased: the feat and fix commits on main since the newest tag, in plain words.
// .github/workflows/sync-changelog.yml runs this daily and opens a pull request when it changes.
import { execFileSync } from 'node:child_process';
import { existsSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const app = process.argv[2];
if (!app || !existsSync(join(app, 'docs/releases'))) {
  console.error('usage: node scripts/sync-changelog.mjs <NetRelish checkout>');
  process.exit(1);
}
const git = (...a) => execFileSync('git', ['-C', app, ...a], { encoding: 'utf8' }).trim();
const tags = new Set(git('tag', '--list', 'v*').split('\n').filter(Boolean));

const semver = (t) => t.replace(/^v/, '').split(/[.-]/).map((n) => (isNaN(+n) ? n : +n));
const newestFirst = (a, b) => {
  const x = semver(a), y = semver(b);
  for (let i = 0; i < Math.max(x.length, y.length); i++) {
    if (x[i] === y[i]) continue;
    if (x[i] === undefined) return -1; // 1.0.0 is newer than 1.0.0-preview.1
    if (y[i] === undefined) return 1;
    return x[i] > y[i] ? -1 : 1;
  }
  return 0;
};

// Markdown to the site's plain strings: no bold, no code ticks, links kept as their text.
const plain = (s) => s
  .replace(/\*\*([^*]+?)\.\*\*\s*/g, '$1: ')
  .replace(/\*\*([^*]+)\*\*/g, '$1')
  .replace(/`([^`]+)`/g, '$1')
  .replace(/\[([^\]]+)\]\([^)]+\)/g, '$1')
  .replace(/\s+/g, ' ')
  .replace(/:\s*:/g, ':')
  .trim()
  .replace(/[.:]$/, '');

function readRelease(tag) {
  const md = readFileSync(join(app, 'docs/releases', `${tag}.md`), 'utf8');
  const blocks = md.split(/\n(?=## )/);
  const intro = blocks[0].split(/\n\s*\n/).map((p) => p.trim()).filter(Boolean).slice(0, 1).map(plain);
  const added = [];
  // "## New in X" lists what a preview added; the first preview calls it "## What works".
  // A nested bullet is its own line on the site.
  const newIn = blocks.find((b) => /^## New in/.test(b)) ?? blocks.find((b) => /^## What works/.test(b));
  if (newIn) {
    for (const line of newIn.split('\n').slice(1)) {
      if (/^\s*- /.test(line)) added.push(line.trim().slice(2));
    }
  }
  const date = git('log', '-1', '--format=%cI', tag);
  const when = new Date(date).toLocaleString('en-US', { month: 'long', year: 'numeric', timeZone: 'America/Phoenix' });
  return { label: tag.replace(/^v/, ''), when, title: `Preview ${tag.replace(/^v/, '')}`, intro, added: added.map(plain) };
}

const files = readdirSync(join(app, 'docs/releases'))
  .map((f) => f.replace(/\.md$/, ''))
  .filter((t) => /^v\d+\.\d+\.\d+/.test(t) && tags.has(t))
  .sort(newestFirst);
const released = files.map(readRelease);

// Commits on main since the newest tag. "feat(pro): Reseal & diff — seal a page again (#74)"
// becomes "Reseal & diff — seal a page again".
const since = [...tags].sort(newestFirst)[0];
const subjects = git('log', '--format=%s', since ? `${since}..HEAD` : 'HEAD').split('\n').filter(Boolean);
const unreleased = subjects
  .filter((s) => /^(feat|fix)(\([^)]*\))?!?:/.test(s))
  .map((s) => s.replace(/^[a-z]+(\([^)]*\))?!?:\s*/, '').replace(/\s*\(#\d+\)$/, '').trim())
  .map((s) => s.charAt(0).toUpperCase() + s.slice(1));

const out = `// Generated by scripts/sync-changelog.mjs from Shepdesign-LLC/NetRelish. Don't edit by hand:
// the daily sync overwrites it. Edit the app's docs/releases/*.md instead.
import type { Release } from './roadmap';

/** The newest tag the app repo has. */
export const latestTag = ${JSON.stringify(since ?? null)};

/** feat and fix commits on main since that tag. */
export const unreleased: string[] = ${JSON.stringify(unreleased, null, 2)};

/** One entry per published preview, newest first. */
export const released: Release[] = ${JSON.stringify(released, null, 2)};
`;
writeFileSync('src/lib/changelog.generated.ts', out);
console.log(`changelog: ${released.length} releases, ${unreleased.length} unreleased changes since ${since}`);
